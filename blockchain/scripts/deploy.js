/**
 * deploy.js — Deployment script for CertificateRegistry
 *
 * Usage:
 *   npx hardhat run scripts/deploy.js --network localhost
 *
 * After deployment this script automatically writes the contract address and
 * ABI into  ../frontend/src/config/contract.js  so the React frontend
 * immediately picks up the new deployment without manual editing.
 */

const { ethers, network } = require("hardhat");
const fs   = require("fs");
const path = require("path");

async function main() {
  if (network.name === "sepolia") {
    const missing = ["ALCHEMY_SEPOLIA_URL", "SEPOLIA_DEPLOYER_PRIVATE_KEY"]
      .filter((name) => !process.env[name]);
    if (missing.length > 0) {
      throw new Error(`Missing ${missing.join(" and ")} in blockchain/.env. Copy blockchain/.env.example and fill it in.`);
    }

    const rpcUrl = new URL(process.env.ALCHEMY_SEPOLIA_URL);
    if (rpcUrl.protocol !== "https:" || !rpcUrl.hostname.endsWith(".g.alchemy.com")) {
      throw new Error("ALCHEMY_SEPOLIA_URL must be an HTTPS Alchemy Sepolia endpoint. Do not use a Mainnet URL.");
    }
  }

  const [deployer] = await ethers.getSigners();

  console.log("\n========================================");
  console.log(" CertificateRegistry — Deployment");
  console.log("========================================");
  console.log(`Deployer (Administrator): ${deployer.address}`);
  console.log(`Balance: ${ethers.formatEther(await ethers.provider.getBalance(deployer.address))} ETH`);
  console.log("");

  const Factory  = await ethers.getContractFactory("CertificateRegistry");
  const contract = await Factory.deploy();
  await contract.waitForDeployment();

  const address = await contract.getAddress();
  console.log(`Contract deployed at: ${address}`);
  console.log(`Administrator set to: ${deployer.address}`);

  // ── Write config to frontend ──────────────────────────────────────────────
  const artifact  = require("../artifacts/contracts/CertificateRegistry.sol/CertificateRegistry.json");
  const targetDir = path.join(__dirname, "../../frontend/src/config");

  const configContent = `// AUTO-GENERATED by scripts/deploy.js — do not edit manually.
// Re-run deployment to update.
// Generated: ${new Date().toISOString()}

const LOCAL_CONTRACT_ADDRESS = "${address}";
const UNCONFIGURED_CONTRACT_ADDRESS = "0x0000000000000000000000000000000000000000";

export const CONTRACT_ADDRESS = import.meta.env.VITE_CONTRACT_ADDRESS
  || (import.meta.env.PROD ? UNCONFIGURED_CONTRACT_ADDRESS : LOCAL_CONTRACT_ADDRESS);
export const NETWORK_CHAIN_ID = Number(import.meta.env.VITE_NETWORK_CHAIN_ID || 31337);
export const NETWORK_NAME = import.meta.env.VITE_NETWORK_NAME
  || (import.meta.env.PROD ? "Network not configured" : "Hardhat Local Network (localhost:8545)");
export const RPC_URL = import.meta.env.VITE_RPC_URL
  || (import.meta.env.PROD ? "" : "http://127.0.0.1:8545");

export const CONTRACT_ABI = ${JSON.stringify(artifact.abi, null, 2)};
`;

  fs.mkdirSync(targetDir, { recursive: true });
  const cfgPath = path.join(targetDir, "contract.js");
  fs.writeFileSync(cfgPath, configContent, "utf8");
  console.log(`Frontend config written to: ${cfgPath}`);
  console.log("\n========================================");
  console.log(" Next steps:");
  console.log(" 1. cd ../frontend && npm run dev");
  if (network.name === "sepolia") {
    console.log(" 1. Configure the frontend with the Sepolia contract address and public RPC endpoint.");
    console.log(" 2. Add Sepolia to MetaMask (Chain ID 11155111) and authorize issuer wallets.");
  } else {
    console.log(" 1. Add Hardhat network to MetaMask: http://127.0.0.1:8545, ChainID 31337");
    console.log(" 2. Import test accounts using private keys shown by `npx hardhat node`");
  }
  console.log("========================================\n");
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
